#!/usr/bin/env python3
"""Generate a 5x7 font.h from a TrueType font (ttf2font5x7.py).

This is a TTF-driven replacement for the reference font5x7.py (which bakes a
fixed ASCII-art table). It renders the same fixed 62-char set
(" 0123456789...~") and emits exactly the font.h format gfx.c expects:
one byte per row, bit 4 = left column, "/* G */" comments -- identical to the
output of the upstream h9toolbox font5x7.py.

Usage:
  poetry run python scripts/render_lock_screens/ttf2font5x7.py            # all *.ttf/*.otf/*.ttc in the current folder
  poetry run python scripts/render_lock_screens/ttf2font5x7.py --ttf arial.ttf
      [--out PATH] [--ppscale N] [--threshold 0..255]

Without --ttf, every TrueType font in the current folder is processed: for
each one it writes <font basename>.h and <font basename>.png right there.
With a single --ttf you may override the output path via --out. The glyph is
rendered large (the drawing box is 9*ppscale tall) then downsampled to 5x7 by
block averaging and thresholded.
"""
import argparse
import os
import sys

try:
    from PIL import Image
except ImportError as e:  # pragma: no cover
    sys.exit("Pillow is required for TTF rendering: poetry add pillow (%s)" % e)

FONT_CHARS = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-.:>/?,()*#!=+_@&%<[];$|~"


def glyph_bitmap(glyph_img, ppscale, threshold):
    """Downsample a ppscale-oversampled glyph to a 5x7 row-byte list.

    glyph_img: white-on-black L image exactly (5*ppscale) x (7*ppscale).
    Returns list of 7 bytes (bit 4 = left column). A cell is "on" when the
    block-average brightness exceeds `threshold` (0..255).
    """
    gw, gh = glyph_img.size
    assert (gw, gh) == (5 * ppscale, 7 * ppscale), (gw, gh)
    rows = []
    for ry in range(7):
        byte = 0
        for rx in range(5):
            box = (rx * ppscale, ry * ppscale,
                   (rx + 1) * ppscale, (ry + 1) * ppscale)
            block = glyph_img.crop(box)
            hist = block.histogram()          # 256 bins of pixel counts
            total = sum(hist)
            avg = sum(i * c for i, c in enumerate(hist)) / total if total else 0
            if avg > threshold:
                byte |= 0x10 >> rx
        rows.append(byte)
    return rows


def render_glyph(font, ch, ppscale, threshold):
    """Render one character, fit into the 5x7 grid, return row bytes."""
    gw, gh = 5 * ppscale, 7 * ppscale
    from PIL import ImageDraw
    # Draw the glyph on a canvas large enough to hold an oversized nominal
    # size, then crop to the ink and fit it into the 5x7 cell.
    fontsize = ppscale * 9
    img = Image.new("L", (gw * 2, gh * 2), 0)
    d = ImageDraw.Draw(img)
    bbox = d.textbbox((0, 0), ch, font=font)
    d.text((0, -bbox[1]), ch, font=font, fill=255)
    ink = img.getbbox()
    if ink is None:      # space / blank
        return [0] * 7
    ink_img = img.crop(ink)
    iw, ih = ink_img.size
    # Uniform scale so the glyph fills the 5x7 cell (block fit).
    scale = min(gw / iw, gh / ih)
    nw, nh = max(1, int(round(iw * scale))), max(1, int(round(ih * scale)))
    nw, nh = min(nw, gw), min(nh, gh)
    small = ink_img.resize((nw, nh), Image.LANCZOS)
    # Center in the 5x7 cell.
    canvas = Image.new("L", (gw, gh), 0)
    ox, oy = (gw - nw) // 2, (gh - nh) // 2
    canvas.paste(small, (ox, oy))
    return glyph_bitmap(canvas, ppscale, threshold)


def emit_font_h(rows_by_char, out_path):
    """Write font.h mirroring the original layout."""
    hdr = ("/* Generated by font5x7.py; do not edit. 5x7 glyphs, one byte per row,\n"
           " * bit 4 = left column. FONT_CHARS[i] is drawn with FONT[i]. */\n"
           "static const char FONT_CHARS[] = \"%s\";\n"
           "static const uint8_t FONT[62][7] = {\n") % FONT_CHARS
    body = []
    for ch in FONT_CHARS:
        rows = rows_by_char[ch]
        shown = ch
        line = "    {" + ", ".join("0x%02x" % b for b in rows) + "}, /* %s */" % shown
        body.append(line)
    tail = "};\n"
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(hdr + "\n".join(body) + "\n" + tail)
    print("wrote %s" % out_path)


def main():
    ap = argparse.ArgumentParser(description="Generate font.h/PNG from TrueType font(s).")
    ap.add_argument("--ttf", default=None,
                    help="path to ONE TrueType font; if omitted, ALL *.ttf/*.otf/"
                         "*.ttc in the current folder are processed")
    ap.add_argument("--out", default=None,
                    help="output .h path (only valid with --ttf); default "
                         "<font basename>.h next to the font")
    ap.add_argument("--ppscale", type=int, default=8,
                    help="oversampling: render box is ppscale*(5 x 7) px")
    ap.add_argument("--threshold", type=int, default=40,
                    help="block-average pixel threshold 0..255 (higher = "
                         "thinner/less ink)")
    args = ap.parse_args()

    fonts = ([args.ttf] if args.ttf
             else sorted(f for f in os.listdir(".")
                         if os.path.splitext(f)[1].lower() in (".ttf", ".otf", ".ttc")))
    if not fonts:
        sys.exit("no TrueType fonts in the current folder and no --ttf given")

    from PIL import ImageFont
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from render_font_chart import render_chart_png

    for ttf in fonts:
        try:
            font = ImageFont.truetype(ttf, args.ppscale * 9)
        except OSError as e:
            print("skip %s: cannot load: %s" % (ttf, e))
            continue
        base = os.path.splitext(os.path.basename(ttf))[0]
        if args.out and len(fonts) == 1:
            out_h = os.path.abspath(args.out)
        elif args.out:
            sys.exit("--out is only valid when a single --ttf is given")
        else:
            out_h = os.path.abspath(base + ".h")   # current folder, named after the font
        rows_by_char = {}
        for ch in FONT_CHARS:
            rows_by_char[ch] = render_glyph(font, ch, args.ppscale, args.threshold)
        emit_font_h(rows_by_char, out_h)
        out_png = os.path.splitext(out_h)[0] + ".png"
        _ = render_chart_png(out_h, out_png)  # PNG right next to the .h
        print("wrote %s" % out_png)


if __name__ == "__main__":
    main()